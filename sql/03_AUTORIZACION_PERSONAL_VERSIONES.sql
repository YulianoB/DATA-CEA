-- Ejecutar exclusivamente en la base de datos de PRUEBAS del CEA.
-- Nunca ejecutar en la base maestra ni en BD_REGISTROS.
-- Versiones inmutables: una versión publicada no se modifica.
CREATE TABLE IF NOT EXISTS public.autorizacion_personal_versiones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version varchar(30) NOT NULL UNIQUE,
  contenido text NOT NULL,
  vigente boolean NOT NULL DEFAULT false,
  fecha_publicacion timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT autorizacion_personal_contenido_no_vacio CHECK (length(btrim(contenido)) > 0),
  CONSTRAINT autorizacion_personal_version_no_vacia CHECK (length(btrim(version)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS autorizacion_personal_una_vigente
  ON public.autorizacion_personal_versiones (vigente) WHERE vigente = true;
ALTER TABLE public.autorizacion_personal_versiones ENABLE ROW LEVEL SECURITY;
-- Sin políticas de acceso directo: las API servidoras del CEA usan cliente de servicio.
COMMENT ON TABLE public.autorizacion_personal_versiones IS
  'Versiones publicadas de la autorización de tratamiento de datos del personal del CEA. No modificar versiones históricas.';
