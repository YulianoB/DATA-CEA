-- Ejecutar en la base de cada CEA, no en MASTER.
-- Bloqueos excepcionales de agenda gestionados por ADMINISTRATIVO.
CREATE TABLE IF NOT EXISTS public.bloqueos_agenda_instructores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instructor_id bigint NOT NULL REFERENCES public.personal(id) ON DELETE RESTRICT,
  fecha_inicio date NOT NULL,
  fecha_fin date NOT NULL,
  hora_inicio time without time zone NOT NULL,
  hora_fin time without time zone NOT NULL,
  motivo text NOT NULL,
  creado_por text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bloqueos_agenda_fechas_validas CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT bloqueos_agenda_horas_validas CHECK (hora_fin > hora_inicio),
  CONSTRAINT bloqueos_agenda_motivo_valido CHECK (length(btrim(motivo)) >= 8)
);
CREATE INDEX IF NOT EXISTS idx_bloqueos_agenda_instructor_fechas
  ON public.bloqueos_agenda_instructores(instructor_id,fecha_inicio,fecha_fin);
COMMENT ON TABLE public.bloqueos_agenda_instructores IS
 'Bloqueos administrativos por fecha o rango; no modifica disponibilidad semanal habitual ni clases ya existentes.';
