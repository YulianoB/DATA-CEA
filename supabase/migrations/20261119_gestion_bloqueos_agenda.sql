-- DATA CEA: administración transaccional de bloqueos (base CEA)
-- EJECUTAR EN SUPABASE SQL EDITOR DE LA EMPRESA CEA ANTES DE USAR
-- "Editar bloqueo" y "Liberar una franja".
-- Conserva los bloqueos existentes y las clases programadas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.bloqueos_agenda_auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bloqueo_id bigint,
  accion text NOT NULL,
  usuario text NOT NULL,
  fecha_operacion timestamptz NOT NULL DEFAULT now(),
  antes jsonb,
  despues jsonb
);
REVOKE ALL ON TABLE public.bloqueos_agenda_auditoria FROM anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.bloqueos_agenda_auditoria TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.bloqueos_agenda_auditoria_id_seq TO service_role;

CREATE INDEX IF NOT EXISTS bloqueos_agenda_auditoria_bloqueo_idx
  ON public.bloqueos_agenda_auditoria (bloqueo_id, fecha_operacion DESC);

CREATE OR REPLACE FUNCTION public.cea_editar_bloqueo_agenda(
  p_id bigint,p_instructor_id bigint,p_fecha_inicio date,p_fecha_fin date,
  p_hora_inicio time,p_hora_fin time,p_motivo text,p_usuario text
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_antes public.bloqueos_agenda_instructores%ROWTYPE;
  v_despues public.bloqueos_agenda_instructores%ROWTYPE;
BEGIN
  IF p_usuario IS NULL OR trim(p_usuario)='' OR p_motivo IS NULL OR length(trim(p_motivo))<8
     OR p_fecha_inicio IS NULL OR p_fecha_fin IS NULL OR p_fecha_inicio>p_fecha_fin
     OR p_fecha_fin-p_fecha_inicio>90 OR p_hora_inicio IS NULL OR p_hora_fin IS NULL
     OR p_hora_inicio>=p_hora_fin OR p_hora_inicio<time '06:00'
     OR p_hora_fin>time '22:00'
  THEN RAISE EXCEPTION 'Datos de edición de bloqueo inválidos'; END IF;

  SELECT * INTO v_antes FROM public.bloqueos_agenda_instructores
   WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'El bloqueo ya no existe'; END IF;
  IF COALESCE(v_antes.tipo_actividad,'BLOQUEO')<>'BLOQUEO'
  THEN RAISE EXCEPTION 'Solo se pueden editar bloqueos administrativos'; END IF;

  PERFORM pg_advisory_xact_lock(521771, p_instructor_id::integer);
  PERFORM pg_advisory_xact_lock(521771, v_antes.instructor_id::integer);

  IF EXISTS (
     SELECT 1 FROM public.programacion_clases c
     WHERE c.instructor_id=p_instructor_id
       AND c.fecha BETWEEN p_fecha_inicio AND p_fecha_fin
       AND c.estado IN ('AGENDADA','PENDIENTE_CARGUE','DICTADA')
       AND c.hora_inicio < p_hora_fin
       AND (c.hora_inicio + (c.duracion_horas * interval '1 hour'))::time > p_hora_inicio
  ) THEN RAISE EXCEPTION 'El rango tiene clases programadas'; END IF;

  IF EXISTS (
    SELECT 1 FROM public.bloqueos_agenda_instructores b
    WHERE b.id<>p_id AND b.instructor_id=p_instructor_id
      AND b.fecha_inicio<=p_fecha_fin AND b.fecha_fin>=p_fecha_inicio
      AND b.hora_inicio<p_hora_fin AND b.hora_fin>p_hora_inicio
  ) THEN RAISE EXCEPTION 'El rango coincide con otro bloqueo'; END IF;

  UPDATE public.bloqueos_agenda_instructores
  SET instructor_id=p_instructor_id,fecha_inicio=p_fecha_inicio,fecha_fin=p_fecha_fin,
      hora_inicio=p_hora_inicio,hora_fin=p_hora_fin,motivo=trim(p_motivo)
  WHERE id=p_id RETURNING * INTO v_despues;

  INSERT INTO public.bloqueos_agenda_auditoria(bloqueo_id,accion,usuario,antes,despues)
    VALUES (p_id,'EDITAR',p_usuario,to_jsonb(v_antes),to_jsonb(v_despues));
  RETURN to_jsonb(v_despues);
END $$;

CREATE OR REPLACE FUNCTION public.cea_liberar_franja_bloqueo(
  p_id bigint,p_fecha date,p_hora time,p_usuario text
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp AS $$
DECLARE
  v_b public.bloqueos_agenda_instructores%ROWTYPE;
  v_fin time;
  v_partes jsonb := '[]'::jsonb;
  v_nueva public.bloqueos_agenda_instructores%ROWTYPE;
BEGIN
  IF p_usuario IS NULL OR trim(p_usuario)='' OR p_fecha IS NULL OR p_hora IS NULL
    OR p_hora<time '06:00' OR p_hora>time '21:00'
    OR extract(minute from p_hora)<>0
  THEN RAISE EXCEPTION 'Datos de franja inválidos'; END IF;
  v_fin := (p_hora + interval '1 hour')::time;
  SELECT * INTO v_b FROM public.bloqueos_agenda_instructores
    WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'El bloqueo ya no existe'; END IF;
  IF COALESCE(v_b.tipo_actividad,'BLOQUEO')<>'BLOQUEO'
    OR p_fecha NOT BETWEEN v_b.fecha_inicio AND v_b.fecha_fin
    OR p_hora<v_b.hora_inicio OR v_fin>v_b.hora_fin
  THEN RAISE EXCEPTION 'La hora no corresponde a este bloqueo administrativo'; END IF;

  PERFORM pg_advisory_xact_lock(521771,v_b.instructor_id::integer);
  -- Al modificar se conserva el motivo, instructor y usuario creador.
  -- El rango original se sustituye de forma ATÓMICA por sus fragmentos.
  DELETE FROM public.bloqueos_agenda_instructores WHERE id=p_id;

  IF v_b.fecha_inicio<p_fecha THEN
    INSERT INTO public.bloqueos_agenda_instructores
      (instructor_id,fecha_inicio,fecha_fin,hora_inicio,hora_fin,motivo,tipo_actividad,creado_por)
    VALUES (v_b.instructor_id,v_b.fecha_inicio,p_fecha-1,v_b.hora_inicio,
      v_b.hora_fin,v_b.motivo,'BLOQUEO',v_b.creado_por)
    RETURNING * INTO v_nueva;
    v_partes:=v_partes||jsonb_build_array(to_jsonb(v_nueva));
  END IF;

  IF v_b.hora_inicio<p_hora THEN
    INSERT INTO public.bloqueos_agenda_instructores
      (instructor_id,fecha_inicio,fecha_fin,hora_inicio,hora_fin,motivo,tipo_actividad,creado_por)
    VALUES (v_b.instructor_id,p_fecha,p_fecha,v_b.hora_inicio,p_hora,
      v_b.motivo,'BLOQUEO',v_b.creado_por)
    RETURNING * INTO v_nueva;
    v_partes:=v_partes||jsonb_build_array(to_jsonb(v_nueva));
  END IF;

  IF v_fin<v_b.hora_fin THEN
    INSERT INTO public.bloqueos_agenda_instructores
      (instructor_id,fecha_inicio,fecha_fin,hora_inicio,hora_fin,motivo,tipo_actividad,creado_por)
    VALUES (v_b.instructor_id,p_fecha,p_fecha,v_fin,v_b.hora_fin,
      v_b.motivo,'BLOQUEO',v_b.creado_por)
    RETURNING * INTO v_nueva;
    v_partes:=v_partes||jsonb_build_array(to_jsonb(v_nueva));
  END IF;

  IF p_fecha<v_b.fecha_fin THEN
    INSERT INTO public.bloqueos_agenda_instructores
      (instructor_id,fecha_inicio,fecha_fin,hora_inicio,hora_fin,motivo,tipo_actividad,creado_por)
    VALUES (v_b.instructor_id,p_fecha+1,v_b.fecha_fin,v_b.hora_inicio,
      v_b.hora_fin,v_b.motivo,'BLOQUEO',v_b.creado_por)
    RETURNING * INTO v_nueva;
    v_partes:=v_partes||jsonb_build_array(to_jsonb(v_nueva));
  END IF;

  INSERT INTO public.bloqueos_agenda_auditoria(bloqueo_id,accion,usuario,antes,despues)
    VALUES (p_id,'LIBERAR_FRANJA',p_usuario,to_jsonb(v_b),v_partes);
  RETURN jsonb_build_object('franja_liberada',jsonb_build_object('fecha',p_fecha,'hora',p_hora),
    'segmentos_conservados',v_partes);
END $$;

-- Retiro completo con registro de auditoría, dentro de la misma transacción.
CREATE OR REPLACE FUNCTION public.cea_retirar_bloqueo_agenda(
  p_id bigint,p_usuario text
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp AS $
DECLARE
  v_antes public.bloqueos_agenda_instructores%ROWTYPE;
BEGIN
  IF p_usuario IS NULL OR trim(p_usuario)='' THEN
    RAISE EXCEPTION 'Se requiere identificar el usuario';
  END IF;
  SELECT * INTO v_antes FROM public.bloqueos_agenda_instructores
    WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'El bloqueo ya no existe'; END IF;
  IF COALESCE(v_antes.tipo_actividad,'BLOQUEO')<>'BLOQUEO'
  THEN RAISE EXCEPTION 'No se puede retirar una actividad académica desde bloqueos'; END IF;
  PERFORM pg_advisory_xact_lock(521771,v_antes.instructor_id::integer);
  DELETE FROM public.bloqueos_agenda_instructores WHERE id=p_id;
  INSERT INTO public.bloqueos_agenda_auditoria(bloqueo_id,accion,usuario,antes,despues)
    VALUES(p_id,'RETIRAR',p_usuario,to_jsonb(v_antes),NULL);
  RETURN jsonb_build_object('id',p_id);
END $;

REVOKE ALL ON FUNCTION public.cea_editar_bloqueo_agenda(bigint,bigint,date,date,time,time,text,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cea_liberar_franja_bloqueo(bigint,date,time,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.cea_editar_bloqueo_agenda(bigint,bigint,date,date,time,time,text,text) TO service_role;
GRANT EXECUTE ON FUNCTION public.cea_liberar_franja_bloqueo(bigint,date,time,text) TO service_role;
REVOKE ALL ON FUNCTION public.cea_retirar_bloqueo_agenda(bigint,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.cea_retirar_bloqueo_agenda(bigint,text) TO service_role;

COMMIT;
