-- DATA-CEA / CEA tenant (NO ejecutar en MASTER)
-- Clientes externos de refuerzo sin matrícula ni recibo.
-- Ejecutar en cada base CEA ANTES de desplegar los cambios de Programación.
BEGIN;

CREATE TABLE IF NOT EXISTS public.clientes_refuerzo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_documento text NOT NULL DEFAULT 'CC',
  documento text NOT NULL,
  nombre_completo text NOT NULL,
  celular text,
  categoria text NOT NULL,
  observaciones text,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT clientes_refuerzo_documento_categoria_uniq UNIQUE(documento,categoria),
  CONSTRAINT clientes_refuerzo_documento_no_vacio CHECK (length(trim(documento)) > 0),
  CONSTRAINT clientes_refuerzo_nombre_no_vacio CHECK (length(trim(nombre_completo)) > 0),
  CONSTRAINT clientes_refuerzo_categoria_no_vacia CHECK (length(trim(categoria)) > 0)
);

ALTER TABLE public.programacion_clases
  ADD COLUMN IF NOT EXISTS cliente_refuerzo_id bigint
  REFERENCES public.clientes_refuerzo(id);

CREATE INDEX IF NOT EXISTS programacion_clases_cliente_refuerzo_fecha_idx
  ON public.programacion_clases(cliente_refuerzo_id, fecha, hora_inicio)
  WHERE cliente_refuerzo_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS clientes_refuerzo_documento_idx
  ON public.clientes_refuerzo(documento);

-- El nuevo identificador es exclusivo frente a matrícula/recibo.
-- No agregar restricción XOR a los registros históricos sin analizarlos.
COMMIT;
