-- DATA-CEA: continuaciones de matrículas vencidas sin generar consecutivos nuevos.
-- Ejecutar UNA VEZ en Supabase SQL Editor antes de utilizar el flujo.
BEGIN;

CREATE TABLE IF NOT EXISTS public.matriculas_continuaciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matricula_id bigint NOT NULL REFERENCES public.aprendices(id) ON DELETE RESTRICT,
  fecha_continuacion date NOT NULL,
  motivo text NOT NULL,
  observaciones text,
  registrado_por text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT matriculas_continuaciones_motivo_check CHECK (length(btrim(motivo)) >= 8),
  CONSTRAINT matriculas_continuaciones_usuario_check CHECK (length(btrim(registrado_por)) > 0)
);

CREATE INDEX IF NOT EXISTS matriculas_continuaciones_matricula_fecha_idx
  ON public.matriculas_continuaciones (matricula_id, fecha_continuacion DESC, id DESC);

-- Control de multiempresa: acceso directo deshabilitado para anónimo.
ALTER TABLE public.matriculas_continuaciones ENABLE ROW LEVEL SECURITY;

COMMIT;

